window.buscarEspeciePorId = function (id) {
    return window.especies.find((especie) => especie.id === id);
};

window.buscarEspeciesPorCategoria = function (categoria) {
    return window.especies.filter(
        (especie) => especie.categoria === categoria
    );
};

window.buscarEspeciesRaras = function () {
    return window.especies.filter(
        (especie) => especie.raridade.toLowerCase() === "rara"
    );
};